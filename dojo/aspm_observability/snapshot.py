"""Singleton operational probes. Each source refreshes outside the scrape path."""
import os
from pathlib import Path
from time import time

import redis
from django.conf import settings
from django.db import connection, transaction
from prometheus_client.core import CounterMetricFamily, GaugeMetricFamily

LIMIT = 10001


def gauge(name, description, value, **labels):
    family = GaugeMetricFamily(name, description, labels=list(labels))
    family.add_metric(list(labels.values()), value)
    return family


def database():
    metrics = []
    with transaction.atomic(), connection.cursor() as cursor:
        cursor.execute("SET LOCAL statement_timeout = '750ms'")
        cursor.execute("""
            SELECT count(*) FROM pg_locks
            WHERE NOT granted AND (database IS NULL OR database = (SELECT oid FROM pg_database WHERE datname = current_database()))
        """)
        metrics.append(gauge("aspm_postgres_lock_waits", "Ungranted PostgreSQL locks for this database or shared objects", cursor.fetchone()[0]))
        cursor.execute("SELECT wal_bytes FROM pg_stat_wal")
        wal = cursor.fetchone()
        if wal and wal[0] is not None:
            metrics.append(CounterMetricFamily("aspm_postgres_wal_bytes", "WAL generated by the PostgreSQL instance", value=float(wal[0])))
        if settings.ASPM_INGESTION_ENABLED:
            cursor.execute("""
                SELECT CASE WHEN job.scan_id IS NULL THEN 'report' ELSE 'scan' END,
                       coalesce(scan.status, 'ACCEPTED'),
                       count(*), extract(epoch FROM min(coalesce(scan.created_at, report.created_at)))
                FROM (SELECT scan_id, report_id FROM dojo_ingestionjob LIMIT %s) job
                LEFT JOIN dojo_scanrun scan ON scan.id = job.scan_id
                LEFT JOIN dojo_generatedreport report ON report.id = job.report_id
                GROUP BY 1, 2
            """, [LIMIT])
            rows = {(kind, state): (count, oldest) for kind, state, count, oldest in cursor.fetchall()}
            for kind, states in (("scan", ("ACCEPTED", "PROCESSING")), ("report", ("ACCEPTED",))):
                for state in states:
                    count, oldest = rows.get((kind, state), (0, None))
                    metrics.append(gauge("aspm_durable_jobs", "Sampled durable jobs by kind and last committed state", count, kind=kind, state=state.lower()))
                    metrics.append(gauge("aspm_durable_oldest_seconds", "Age of oldest sampled durable job", max(0, time() - float(oldest)) if oldest else 0, kind=kind, state=state.lower()))
            metrics.append(gauge("aspm_ingestion_outbox_pending", "Sampled durable ingestion and report backlog", sum(count for count, _ in rows.values())))
        if settings.ASPM_WEBHOOKS_ENABLED:
            cursor.execute("""
                SELECT count(*), extract(epoch FROM min(created_at))
                FROM (SELECT created_at FROM dojo_webhookdelivery
                      WHERE state IN ('PENDING','RETRY','IN_FLIGHT') LIMIT %s) delivery
            """, [LIMIT])
            count, oldest = cursor.fetchone()
            metrics.extend((
                gauge("aspm_webhook_outbox_pending", "Sampled active webhook deliveries", count),
                gauge("aspm_webhook_outbox_oldest_seconds", "Age of oldest sampled active delivery", max(0, time() - float(oldest)) if oldest else 0),
            ))
            for table, condition, metric, description in (
                ("dojo_webhookevent", "expanded=false", "aspm_webhook_outbox_unexpanded", "Sampled events awaiting expansion"),
                ("dojo_webhookdelivery", "state='DEAD'", "aspm_webhook_outbox_dead", "Sampled dead deliveries"),
            ):
                cursor.execute(f"SELECT count(*) FROM (SELECT 1 FROM {table} WHERE {condition} LIMIT %s) AS sample", [LIMIT])  # noqa: S608 -- fixed SQL above
                metrics.append(gauge(metric, description, cursor.fetchone()[0]))
    return metrics


def security():
    metrics = []
    with transaction.atomic(), connection.cursor() as cursor:
        cursor.execute("SET LOCAL statement_timeout = '750ms'")
        cursor.execute("""
            SELECT CASE WHEN severity IN ('Critical','High','Medium','Low','Info') THEN severity ELSE 'Other' END, count(*)
            FROM dojo_finding
            WHERE active AND NOT false_p AND NOT duplicate AND NOT out_of_scope AND NOT is_mitigated
            GROUP BY 1
        """)
        severities = dict(cursor.fetchall())
        for severity in ("Critical", "High", "Medium", "Low", "Info", "Other"):
            metrics.append(gauge("aspm_security_active_findings", "Live active findings by canonical severity", severities.get(severity, 0), severity=severity))
        cursor.execute("SELECT (SELECT count(*) FROM dojo_product), (SELECT count(*) FROM dojo_repository)")
        projects, repositories = cursor.fetchone()
        metrics.extend((
            gauge("aspm_security_projects", "All ASPM projects", projects),
            gauge("aspm_security_repositories", "All registered repositories", repositories),
        ))
    return metrics


def broker():
    from dojo.celery import app  # noqa: PLC0415 -- Django is initialized by the singleton exporter

    with app.connection_for_read() as broker_connection:
        if broker_connection.transport.driver_type != "redis":
            msg = "Queue snapshot requires the Valkey/Redis transport"
            raise ValueError(msg)
        # Use the same versioned Kombu key mapping and broker TLS options as the worker.
        transport = broker_connection.transport
        priority_steps = transport.Channel.priority_steps
        separator = transport.Channel.sep
        options = app.conf.broker_transport_options
        keys = options.get("priority_steps", priority_steps)
        sep = options.get("sep", separator)
        prefix = options.get("global_keyprefix", "")
        queues = os.environ.get("ASPM_METRICS_QUEUES", "").split(",")
        queues = [queue.strip() for queue in queues if queue.strip()]
        tls = broker_connection.ssl if isinstance(broker_connection.ssl, dict) else {}
        kwargs = {key: value for key, value in tls.items() if key in {"ssl_cert_reqs", "ssl_ca_certs", "ssl_certfile", "ssl_keyfile", "ssl_check_hostname"}}
        with redis.Redis.from_url(broker_connection.as_uri(include_password=True), socket_connect_timeout=2, socket_timeout=2, **kwargs) as client, client.pipeline(transaction=False) as pipeline:
            for queue in queues:
                for priority in keys:
                    pipeline.llen(prefix + (f"{queue}{sep}{priority}" if priority else queue))
            pipeline.hlen(prefix + options.get("unacked_key", transport.Channel.unacked_key))
            values = pipeline.execute()
    metrics = [
        gauge("aspm_broker_queue_ready", "Broker-ready messages across configured Kombu priority lists", sum(values[index * len(keys):(index + 1) * len(keys)]), queue=queue)
        for index, queue in enumerate(queues)
    ]
    return [*metrics, gauge("aspm_broker_unacked", "Unacknowledged messages across the broker keyspace", values[-1])]


def storage():
    from dojo.management.commands.aspm_preflight import storage_ready  # noqa: PLC0415

    storage_ready()
    stats = os.statvfs(Path(settings.ASPM_ARTIFACT_ROOT))
    return [
        gauge("aspm_evidence_filesystem_bytes", "Capacity of the mounted evidence filesystem", stats.f_blocks * stats.f_frsize, state="total"),
        gauge("aspm_evidence_filesystem_bytes", "Available space on the mounted evidence filesystem", stats.f_bavail * stats.f_frsize, state="available"),
    ]
